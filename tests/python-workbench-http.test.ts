import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { after, test } from "node:test";
const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "atlas-python-http-")));
process.env.LH_DATA_DIR = path.join(root, "data");
process.env.LH_AUTH_FILE = path.join(root, "auth.json");
process.env.LH_IGNORE_ENV_KEYS = "1";
fs.writeFileSync(process.env.LH_AUTH_FILE, "{}");
after(() => fs.rmSync(root, { recursive: true, force: true }));
test("Workbench HTTP permission, origin, retention and request replay guards", async () => {
    const { stores } = await import("../src/server/stores.ts");
    const { pythonWorkbenchResponse: respond, pythonWorkbench } = await import("../src/server/python-workbench.ts");
    const { setTurnRunner } = await import("../src/server/jobs.ts");
    setTurnRunner(async () => 403);
    const chat = stores.chatStore.createChat("Workbench HTTP fixture"), other = stores.chatStore.createChat("Other fixture");
    const post = (body: unknown, origin = "http://local.test") => respond(new Request("http://local.test/api", { method: "POST", headers: { "Origin": origin }, body: JSON.stringify(body) }), chat.id);
    assert.equal((await respond(new Request("http://local.test/api"), "missing")).status, 404);
    assert.equal((await post({ action: "configure", project: null }, "http://evil.test")).status, 403);
    assert.equal((await post({ action: "run", requestId: crypto.randomUUID(), input: { title: "Test", code: "pass" } })).status, 400);
    const project = path.join(root, "project");
    fs.mkdirSync(project);
    assert.equal((await post({ action: "configure", project: { path: project, interpreter: "/usr/bin/python3", network: false } })).status, 200);
    let calls = 0;
    pythonWorkbench.run = async (_chat, id, input) => { calls++; return { runId: id, title: input.title, status: "done", stdout: "2", stderr: "", outputs: [] }; };
    const body = { action: "run", requestId: crypto.randomUUID(), input: { title: "Test", code: "print(2)" } };
    const first = await (await post(body)).json(), second = await (await post(body)).json();
    assert.equal(first.runId, second.runId);
    assert.equal(calls, 1);
    assert.equal(stores.jobStore.getJob(first.runId)?.status, "done");
    assert.equal((await respond(new Request(`http://local.test/api?run=${first.runId}`), other.id)).status, 400);
    assert.equal((await post({ action: "configure", project: null })).status, 200);
    assert.equal((await (await respond(new Request("http://local.test/api"), chat.id)).json()).project, null);
    await new Promise(resolve => setTimeout(resolve, 1200));
});
