import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { after, it } from "node:test";
const root = fs.mkdtempSync(path.join(os.tmpdir(), "companion-flow-"));
process.env.LH_DATA_DIR = path.join(root, "data");
process.env.LH_AUTH_FILE = path.join(root, "auth.json");
process.env.LH_IGNORE_ENV_KEYS = "1";
const { createFauxCore, fauxAssistantMessage, fauxToolCall } = await import("@earendil-works/pi-ai");
const { createJobRunner } = await import("../src/agent/subagents/runner.ts");
const { stores } = await import("../src/server/stores.ts");
const { jobTools } = await import("../src/agent/tools/jobs.ts");
const { researchSourceResponse } = await import("../src/server/research-sources.ts");
const { createResearchSourceStore } = await import("../src/store/research-sources.ts");
after(() => { fs.rmSync(root, { recursive: true, force: true }); });
it("uses the existing job lifecycle, durable input, delivery and exact-request deduplication", async () => {
    const chat = stores.chatStore.createChat("Mathematical investigation fixture"), input = { mode: "mathematical" as const, question: "Can the marginals determine the joint law?", context: "No dependence assumptions." };
    const faux = createFauxCore({ tokenSize: { min: 64, max: 64 } });
    faux.setResponses([fauxAssistantMessage([fauxToolCall("submit_findings", { summary: "No external theorem was verified.", findings: [], limitations: "Fixture has no search provider; no novelty claim." })], { stopReason: "toolUse" })]);
    const delivered: unknown[] = [];
    const runner = createJobRunner({ ...stores, deliver: async (steer) => { delivered.push(steer); }, engineFor: () => ({ model: faux.getModel(), streamFn: faux.streamSimple }), researchSources: stores.researchSources });
    const spawned: string[] = [];
    const tools = jobTools({ chatId: chat.id, jobStore: stores.jobStore, spawn: job => { spawned.push(job.id); } });
    await tools.research!.execute!("first", input);
    await tools.research!.execute!("repeat", input);
    assert.equal(spawned.length, 1);
    const id = spawned[0]!;
    assert.deepEqual(stores.jobStore.getJob(id)!.input, input);
    await runner.runJob(id);
    assert.equal(stores.jobStore.getJob(id)!.status, "done");
    assert.equal(delivered.length, 1);
    const result = stores.jobStore.getJob(id)!.result as {
        investigation: {
            findings: unknown[];
        };
    };
    assert.equal(result.investigation.findings.length, 0);
    await runner.runJob(id);
    await tools.research!.execute!("repeat-done", input);
    assert.equal(spawned.length, 1);
    assert.equal(delivered.length, 1);
    await tools.research!.execute!("new-context", { ...input, context: "Fixed independence assumption." });
    assert.equal(spawned.length, 2);
    assert.equal(stores.graphStore.readNodes().length, 0, "investigation never writes canonical mathematics");
});
it("scopes reader APIs to a session-owned retained passage and original content", async () => {
    const chat = stores.chatStore.createChat("Reader fixture"), other = stores.chatStore.createChat("Other fixture");
    const bytes = new TextEncoder().encode("%PDF-fixture bytes; no parse needed in storage test");
    const source = stores.researchSources.retain(chat.id, { bytes, title: "Fixture source", authors: "", url: "https://example.test/paper.pdf", pages: 2 });
    const passage = stores.researchSources.putPassage(chat.id, { source, page: 2, reference: "Lemma 1", quote: "An exact identifying quotation", location: "page-only", rects: [] });
    assert.equal(createResearchSourceStore(path.join(root, "data", "research-sources")).passage(chat.id, passage.id).id, passage.id);
    const req = (id: string, asset = false) => new Request(`http://localhost/api/chats/${id}/research-source?passage=${passage.id}${asset ? "&asset=1" : ""}`);
    const response = researchSourceResponse(req(chat.id), chat.id);
    assert.equal(response.status, 200);
    assert.equal((await response.json()).passage.id, passage.id);
    assert.equal(response.headers.get("Cache-Control"), "private, no-store");
    const binary = researchSourceResponse(req(chat.id, true), chat.id);
    assert.equal(binary.headers.get("Content-Type"), "application/pdf");
    assert.deepEqual(new Uint8Array(await binary.arrayBuffer()), bytes);
    assert.equal(researchSourceResponse(req(other.id), other.id).status, 404);
    assert.equal(researchSourceResponse(req("missing"), "missing").status, 404);
});
